package main

import (
	"fmt"
	"os"
	"os/exec"
	"strconv"
	"strings"
	"syscall"
	"time"

	"github.com/spf13/cobra"
)

// authorizedKeysPath is the AuthorizedKeysFile packaging/ssh/kb-operator.conf
// points the operator sshd at.
const authorizedKeysPath = "/etc/kb/authorized_keys"

var (
	sshPort    int
	sshUser    string
	sshKeyFile string
)

var sshUpCmd = &cobra.Command{
	Use:   "up",
	Short: "Enable and start the operator sshd (sshd@kb-operator.service)",
	RunE: func(cmd *cobra.Command, args []string) error {
		if err := systemctl("enable", "--now", unitSSH); err != nil {
			return fmt.Errorf("start %s: %w", unitSSH, err)
		}
		if err := waitForPort("127.0.0.1", sshPort, 15*time.Second); err != nil {
			return err
		}
		fmt.Printf("SSH console up: kbctl ssh connect   (or ssh -t -p %d %s@<host>)\n", sshPort, sshUser)
		return nil
	},
}

var sshDownCmd = &cobra.Command{
	Use:   "down",
	Short: "Stop and disable the operator sshd",
	RunE: func(cmd *cobra.Command, args []string) error {
		return systemctl("disable", "--now", unitSSH)
	},
}

var sshStatusCmd = &cobra.Command{
	Use:   "status",
	Short: "Show whether the operator sshd is running and its port is answering",
	RunE: func(cmd *cobra.Command, args []string) error {
		state, listening := unitState(unitSSH), portOpen("127.0.0.1", sshPort)
		fmt.Printf("%s: %s, 127.0.0.1:%d listening=%v\n", unitSSH, state, sshPort, listening)
		if state != "active" || !listening {
			os.Exit(3)
		}
		return nil
	},
}

var sshConnectCmd = &cobra.Command{
	Use:   "connect [host]",
	Short: "Open the TUI over SSH on the operator console (default host 127.0.0.1)",
	Long: `Replaces this process with ssh to the operator sshd, which ForceCommands the
audit wrapper and then kbopd. Starts the console first if it is not running
and the target is this machine.`,
	Args: cobra.MaximumNArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		host := "127.0.0.1"
		if len(args) == 1 {
			host = args[0]
		}
		local := host == "127.0.0.1" || host == "localhost" || host == "::1"
		if local && !portOpen(host, sshPort) {
			fmt.Fprintln(os.Stderr, "operator sshd not listening; starting it...")
			if err := systemctl("enable", "--now", unitSSH); err != nil {
				return fmt.Errorf("start %s: %w", unitSSH, err)
			}
			if err := waitForPort(host, sshPort, 15*time.Second); err != nil {
				return err
			}
		}
		ssh, err := exec.LookPath("ssh")
		if err != nil {
			return fmt.Errorf("ssh client not found in PATH: %w", err)
		}
		argv := []string{"ssh", "-t", "-p", strconv.Itoa(sshPort)}
		if sshKeyFile != "" {
			argv = append(argv, "-i", sshKeyFile)
		}
		if local {
			// The host key is generated by provision.sh per machine, so a
			// loopback connection would otherwise pollute known_hosts with
			// a key that changes on every reinstall.
			argv = append(argv, "-o", "UserKnownHostsFile=/dev/null", "-o", "StrictHostKeyChecking=no", "-o", "LogLevel=ERROR")
		}
		argv = append(argv, sshUser+"@"+host)
		return syscall.Exec(ssh, argv, syscall.Environ())
	},
}

var sshAddKeyCmd = &cobra.Command{
	Use:   "add-key <pubkey-file|->",
	Short: "Authorize an operator public key for the SSH console (/etc/kb/authorized_keys)",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		var data []byte
		var err error
		if args[0] == "-" {
			data, err = readAll(os.Stdin)
		} else {
			data, err = os.ReadFile(args[0])
		}
		if err != nil {
			return err
		}
		key := strings.TrimSpace(string(data))
		if i := strings.IndexByte(key, '\n'); i >= 0 {
			return fmt.Errorf("expected exactly one public key, got multiple lines")
		}
		if !validPubKey(key) {
			return fmt.Errorf("not an OpenSSH public key (want ssh-ed25519/ecdsa-sha2-*/sk-*/ssh-rsa ...)")
		}
		if existing, err := os.ReadFile(authorizedKeysPath); err == nil && strings.Contains(string(existing), key) {
			fmt.Println("key already authorized")
			return nil
		}
		// sudo tee -a: the file is operator:kb 0600, so even a kb-group
		// member can't append without privilege.
		tee := exec.Command("tee", "-a", authorizedKeysPath)
		if os.Geteuid() != 0 {
			tee = exec.Command("sudo", "tee", "-a", authorizedKeysPath)
		}
		tee.Stdin = strings.NewReader(key + "\n")
		tee.Stderr = os.Stderr
		if err := tee.Run(); err != nil {
			return fmt.Errorf("append to %s: %w", authorizedKeysPath, err)
		}
		fmt.Println("key authorized for", sshUser)
		return nil
	},
}

func validPubKey(k string) bool {
	for _, p := range []string{"ssh-ed25519 ", "ssh-rsa ", "ecdsa-sha2-", "sk-ssh-ed25519@", "sk-ecdsa-sha2-"} {
		if strings.HasPrefix(k, p) {
			return len(strings.Fields(k)) >= 2
		}
	}
	return false
}

func readAll(f *os.File) ([]byte, error) {
	var b strings.Builder
	buf := make([]byte, 4096)
	for {
		n, err := f.Read(buf)
		b.Write(buf[:n])
		if err != nil {
			break
		}
	}
	return []byte(b.String()), nil
}

func init() {
	sshCmd.PersistentFlags().IntVar(&sshPort, "port", 2222, "operator sshd port (packaging/ssh/kb-operator.conf)")
	sshCmd.PersistentFlags().StringVar(&sshUser, "user", "operator", "account the console ForceCommand is bound to")
	sshConnectCmd.Flags().StringVarP(&sshKeyFile, "identity", "i", "", "private key file passed to ssh -i")
	sshCmd.AddCommand(sshUpCmd, sshDownCmd, sshStatusCmd, sshConnectCmd, sshAddKeyCmd)
}
